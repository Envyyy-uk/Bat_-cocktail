/* ---------- Власні коктейлі користувача (localStorage) ---------- */
function loadCustomCocktails() {
  try {
    const raw = localStorage.getItem("sw_custom_cocktails");
    return raw ? JSON.parse(raw) : [];
  } catch (e) {
    return [];
  }
}

function saveCustomCocktails(list) {
  localStorage.setItem("sw_custom_cocktails", JSON.stringify(list));
}

function getAllCocktails() {
  return COCKTAILS.concat(loadCustomCocktails());
}

function getCocktailBySlug(slug) {
  return getAllCocktails().find(c => c.slug === slug);
}

function slugify(text) {
  const map = { а:"a",б:"b",в:"v",г:"h",ґ:"g",д:"d",е:"e",є:"ie",ж:"zh",з:"z",и:"y",і:"i",ї:"i",й:"i",к:"k",л:"l",м:"m",н:"n",о:"o",п:"p",р:"r",с:"s",т:"t",у:"u",ф:"f",х:"kh",ц:"ts",ч:"ch",ш:"sh",щ:"shch",ь:"",ю:"iu",я:"ia" };
  return text
    .toLowerCase()
    .split("")
    .map(ch => map[ch] !== undefined ? map[ch] : ch)
    .join("")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "") || "coctail-" + Date.now();
}
